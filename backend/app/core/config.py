"""Application configuration settings using Pydantic Settings."""

import os
from typing import List
from pydantic_settings import BaseSettings


class Settings(BaseSettings):
    """Configuration settings for the SPECTRE application."""

    PROJECT_NAME: str = "SPECTRE Legal Assistant"
    API_V1_STR: str = "/api/v1"
    VERSION: str = "1.0.0"
    ENVIRONMENT: str = "development"
    DEBUG: bool = True

    # Security & JWT
    SECRET_KEY: str = os.getenv("SECRET_KEY", "spectre-super-secret-jwt-key-for-development-only-replace-in-prod-2026")
    ALGORITHM: str = "HS256"
    ACCESS_TOKEN_EXPIRE_MINUTES: int = 60 * 24  # 24 hours

    # Database
    DATABASE_URL: str = os.getenv(
        "DATABASE_URL",
        "sqlite:///./spectre.db"
    )

    # CORS
    BACKEND_CORS_ORIGINS: List[str] = [
        "http://localhost:3000",
        "http://localhost:5173",
        "http://127.0.0.1:3000",
        "http://127.0.0.1:5173",
        "*",
    ]

    # AI Service Settings
    SPECTRE_AI_DIR: str = os.getenv("SPECTRE_AI_DIR", "spectre_ai_engine_final")
    ANTHROPIC_API_KEY: str = os.getenv("ANTHROPIC_API_KEY", "")
    DEFAULT_TOP_K: int = 5
    MAX_QUERY_LENGTH: int = 2000

    # Safety & Legal Disclaimers
    STANDARD_DISCLAIMER: str = (
        "DISCLAIMER: This information is generated by an AI-assisted legal platform for informational "
        "and guidance purposes only. It does not constitute formal legal advice, representation, or guarantee "
        "of outcome. Consult a licensed advocate for case-specific advice."
    )

    class Config:
        case_sensitive = True
        env_file = ".env"


settings = Settings()
